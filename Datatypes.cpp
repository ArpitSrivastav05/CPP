//UNDERSTANDING THE DATATYPES IN C++
#include <iostream>
using namespace std;

int main (){
    int a = 10; //integer
    float b = 3.14; //floating point number
    char c = 'A'; //character
    bool d = true; //boolean
    double e = 3.141592653589793; //double precision floating point number


    cout << "Integer: " << a << endl;
    cout << "Float: " << b << endl;
    cout << "Character: " << c << endl;
    cout << "Boolean: " << d << endl;
    cout << "Double: " << e << endl;

    return 0;
}